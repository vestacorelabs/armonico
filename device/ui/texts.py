def check_counts(lang, problems, warnings, passed, skipped):
    """The summary's line: "2 problems, 1 warning · 27 passed", the same on the screen and in Telegram."""
    head = []
    if problems:
        head.append(tr(lang, "chk.problem1") if problems == 1 else tr(lang, "chk.problems", n=problems))
    if warnings:
        head.append(tr(lang, "chk.warning1") if warnings == 1 else tr(lang, "chk.warnings", n=warnings))
    out = ", ".join(head) if head else tr(lang, "chk.noProblems")
    out += " · " + tr(lang, "chk.passedN", n=passed)
    if skipped:
        out += " · " + (tr(lang, "chk.skipped1") if skipped == 1 else tr(lang, "chk.skippedN", n=skipped))
    return out


def tr(lang, key, **kw):
    """One line in the screen's language; an unknown key shows as itself, so a gap is seen, not hidden."""
    if str(kw.get("n", "")) == "1" and key + ".1" in T:
        key += ".1"                      # one of something is said as one: "דקה אחת", not "1 דקות"
    pair = T.get(key)
    s = key if pair is None else pair[1 if lang == "he" else 0]
    return s.format(**kw) if kw else s


def steps(lang, key, **kw):
    i = 1 if lang == "he" else 0
    return [p[i].format(**kw) if kw else p[i] for p in STEPS[key]]


